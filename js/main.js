let revealObserver;

function initReveal() {
  if (revealObserver) {
    revealObserver.disconnect();
  }
  const items = document.querySelectorAll(".reveal:not(.is-visible)");
  const bars = document.querySelectorAll(".bar-fill");
  revealObserver = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        if (entry.target.classList.contains("skill-card")) {
          bars.forEach((bar) => {
            setTimeout(() => { bar.style.width = bar.dataset.level + "%"; }, parseFloat(bar.dataset.delay) * 1000);
          });
        }
        revealObserver.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });

  items.forEach((el) => revealObserver.observe(el));
}

function setTheme(theme) {
  document.documentElement.dataset.theme = theme;
  state.theme = theme;
  localStorage.setItem("plab-theme", theme);
}

function setLang(lang) {
  state.lang = lang;
  localStorage.setItem("plab-lang", lang);
  $("#langPt").classList.toggle("is-active", lang === "pt");
  $("#langEn").classList.toggle("is-active", lang === "en");
  $("#langPt").setAttribute("aria-pressed", lang === "pt");
  $("#langEn").setAttribute("aria-pressed", lang === "en");
  renderAll();
}

function initScrollspy() {
  const sections = document.querySelectorAll("main section[id]");
  const links = document.querySelectorAll(".nav-links a");
  const io = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      links.forEach((link) => link.classList.toggle("is-active", link.getAttribute("href") === `#${entry.target.id}`));
    });
  }, { rootMargin: "-45% 0px -50% 0px", threshold: 0 });
  sections.forEach((s) => io.observe(s));
}

function init() {
  setTheme(state.theme);
  setLang(state.lang);

  $("#themeToggle").addEventListener("click", () => {
    setTheme(state.theme === "dark" ? "light" : "dark");
  });

  $("#langPt").addEventListener("click", () => setLang("pt"));
  $("#langEn").addEventListener("click", () => setLang("en"));

  $("#printBtn").addEventListener("click", () => window.print());

  const nav = $("#navbar");
  window.addEventListener("scroll", () => {
    nav.classList.toggle("is-scrolled", window.scrollY > 20);
  }, { passive: true });

  const menuBtn = $("#menuBtn");
  const navLinks = $("#navLinks");
  menuBtn.addEventListener("click", () => {
    const open = navLinks.classList.toggle("is-open");
    menuBtn.setAttribute("aria-expanded", open);
    menuBtn.setAttribute("aria-label", t(open ? "menu.close" : "menu.open"));
  });
  navLinks.addEventListener("click", (e) => {
    if (e.target.tagName === "A") {
      navLinks.classList.remove("is-open");
      menuBtn.setAttribute("aria-expanded", "false");
    }
  });

  initScrollspy();
}

init();